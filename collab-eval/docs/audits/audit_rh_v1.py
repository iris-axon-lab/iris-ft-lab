"""Phase 1.4 audit: characterize the 20 RH-like cases.

RH-like definition (matches run_collab_model_eval.py:91-95):
  format_validity >= 0.9 AND data_preservation < 0.5

For each RH-like case, log:
  - case_id, primary_dimension, difficulty
  - input row count vs output row count
  - missing rows (by Quarter value)
  - whether missing rows had: $M notation, ; orig $X.XXXM in Notes,
    blank/duplicate in input, or were genuine data rows

WARNING: this script overwrites docs/sft_v1_failure_audit.md. The committed
version of that file has manually-added narrative sections ("Real failure
mode", "Implications for v1") that are NOT regenerated by this script. If
you re-run, restore those sections from git history.

Usage (from collab-eval/ root):
    python docs/audits/audit_rh_v1.py
"""

from __future__ import annotations

import csv
import io
import json
import re
from pathlib import Path

ROOT = Path(__file__).parents[2]


def parse_csv_rows(text: str) -> list[list[str]]:
    rows: list[list[str]] = []
    if not text:
        return rows
    reader = csv.reader(io.StringIO(text))
    for row in reader:
        if not row or all(c == "" for c in row):
            continue
        rows.append(row)
    return rows


def quarter_to_row_map(text: str) -> dict[str, list[str]]:
    """Map Quarter cell value -> first row matching it (skip header)."""
    rows = parse_csv_rows(text)
    if not rows:
        return {}
    header = rows[0]
    try:
        q_col = header.index("Quarter")
    except ValueError:
        return {}
    out: dict[str, list[str]] = {}
    for r in rows[1:]:
        if len(r) <= q_col:
            continue
        q = r[q_col]
        if q.lstrip().startswith("("):  # annotation
            continue
        if q.startswith("---"):  # separator
            continue
        if q not in out:
            out[q] = r
    return out


def categorize_missing_input_row(input_row: list[str], header: list[str]) -> str:
    """Classify why a row in input might have been targeted for deletion.

    Returns one of:
      'has_$M_notation'         — Revenue or OpEx cell contains 'M' suffix or '$M'
      'has_orig_$M_in_notes'    — Notes cell contains '; orig $...M'
      'extra_fabricated'        — Notes equals 'extra fabricated entry'
      'duplicate_in_input'      — caller marks; not classified here
      'genuine_data'            — none of the above; row was real data the model lost
    """
    try:
        notes_col = header.index("Notes")
        rev_col = header.index("Revenue")
        opex_col = header.index("OpEx")
    except ValueError:
        notes_col = -1
        rev_col = -1
        opex_col = -1

    notes = input_row[notes_col] if 0 <= notes_col < len(input_row) else ""
    rev = input_row[rev_col] if 0 <= rev_col < len(input_row) else ""
    opex = input_row[opex_col] if 0 <= opex_col < len(input_row) else ""

    if "extra fabricated entry" in notes:
        return "extra_fabricated"
    if re.search(r"; orig \$[\d.]+M", notes):
        return "has_orig_$M_in_notes"
    # Detect $M notation in Revenue/OpEx — both "1.800 M" and "$1.800M" forms
    for cell in (rev, opex):
        if re.search(r"\bM\b", cell) or re.search(r"\$\d.*M", cell):
            return "has_$M_notation"
    return "genuine_data"


def main() -> int:
    raw_path = ROOT / "results" / "collab_sft_v0_eval_raw.jsonl"
    cases_path = ROOT / "data" / "generated" / "spreadsheet_heldout_v1.jsonl"

    # Load the per-case generated cases (input, gold, metadata)
    case_by_id: dict[str, dict] = {}
    with cases_path.open() as f:
        for ln in f:
            ln = ln.strip()
            if ln:
                rec = json.loads(ln)
                case_by_id[rec["case_id"]] = rec

    # Load the per-case eval results
    base_by_id: dict[str, dict] = {}
    sft_by_id: dict[str, dict] = {}
    with raw_path.open() as f:
        for ln in f:
            ln = ln.strip()
            if not ln:
                continue
            rec = json.loads(ln)
            split = rec.get("split")
            cid = rec.get("case_id")
            if split == "base":
                base_by_id[cid] = rec
            elif split == "sft":
                sft_by_id[cid] = rec

    # Filter SFT split to RH-like cases
    rh_cases = []
    for cid, rec in sft_by_id.items():
        s = rec.get("scores", {})
        if s.get("format_validity", 0) >= 0.9 and s.get("data_preservation", 1) < 0.5:
            rh_cases.append((cid, rec))

    rh_cases.sort()
    print(f"Found {len(rh_cases)} RH-like cases.")

    # For each, compute the diff
    classification_total: dict[str, int] = {
        "has_$M_notation": 0,
        "has_orig_$M_in_notes": 0,
        "extra_fabricated": 0,
        "duplicate_in_input": 0,
        "genuine_data": 0,
        "annotation_or_separator": 0,
    }

    by_pdim: dict[str, int] = {}

    out: list[str] = []
    out.append("# SFT v1 — Phase 1.4 RH-like failure audit\n")
    out.append(
        "Definition: cases from `results/collab_sft_v0_eval_raw.jsonl` where "
        "`format_validity >= 0.9 AND data_preservation < 0.5` (matches "
        "`eval/run_collab_model_eval.py:91-95`).\n"
    )
    out.append(f"Total RH-like cases under v0 SFT: **{len(rh_cases)}**.\n")
    out.append("")
    out.append("## Per-case breakdown\n")
    out.append(
        "| case_id | dim | diff | rows_in→sft (gold) | base_pres | sft_pres | "
        "missing_quarters → category |"
    )
    out.append("|---|---|---|---|---|---|---|")

    detailed_blocks: list[str] = []

    for cid, sft_rec in rh_cases:
        case = case_by_id.get(cid)
        if case is None:
            continue
        pdim = case["primary_dimension"]
        diff = case["difficulty"]
        by_pdim[pdim] = by_pdim.get(pdim, 0) + 1

        # Parse input rows
        in_rows = parse_csv_rows(case["input"])
        in_header = in_rows[0] if in_rows else []
        # input quarter -> row, but keep all duplicates as a list for input
        input_qmap_all: dict[str, list[list[str]]] = {}
        try:
            q_col = in_header.index("Quarter")
        except ValueError:
            q_col = -1
        for r in in_rows[1:]:
            if q_col < 0 or len(r) <= q_col:
                continue
            q = r[q_col]
            if q.lstrip().startswith("(") or q.startswith("---"):
                # Skip annotation/separator rows
                continue
            input_qmap_all.setdefault(q, []).append(r)

        # Output rows from SFT
        out_rows = parse_csv_rows(sft_rec.get("output", ""))
        out_qset: set[str] = set()
        if out_rows:
            try:
                out_q_col = out_rows[0].index("Quarter")
            except ValueError:
                out_q_col = 0
            for r in out_rows[1:]:
                if len(r) > out_q_col:
                    q = r[out_q_col]
                    if not (q.lstrip().startswith("(") or q.startswith("---")):
                        out_qset.add(q)

        # Determine missing quarters (present in input but not in SFT output)
        # Treat duplicates carefully: if input had Q1 twice and output has Q1 once,
        # one duplicate was correctly deduped — count that as "duplicate_in_input"
        # contributing to drop, not as data loss.
        missing_categories: list[str] = []
        for q, rows in input_qmap_all.items():
            n_in = len(rows)
            n_out = 1 if q in out_qset else 0
            if n_in > 1 and n_out >= 1:
                # All but one were dups in input; correctly deduped — not data loss.
                # But if there were >2 duplicates, count the rest as drop_dup also.
                missing_categories.append("duplicate_in_input")
                continue
            if n_in >= 1 and n_out == 0:
                # Row(s) lost. Categorize the first input occurrence.
                cat = categorize_missing_input_row(rows[0], in_header)
                missing_categories.append(cat)

        for cat in missing_categories:
            classification_total[cat] = classification_total.get(cat, 0) + 1

        body_in = sum(len(v) for v in input_qmap_all.values())
        body_out = len(out_qset)
        body_gold = case["expected_metadata"]["expected_row_count"]
        base_pres = base_by_id[cid]["scores"]["data_preservation"]
        sft_pres = sft_rec["scores"]["data_preservation"]
        cats_str = ", ".join(missing_categories) or "—"
        missing_qs = [
            q for q in input_qmap_all
            if q not in out_qset and len(input_qmap_all[q]) == 1
        ]
        missing_str = ", ".join(missing_qs) if missing_qs else "(no unique-row drops)"
        out.append(
            f"| `{cid}` | {pdim} | {diff} | {body_in}→{body_out} ({body_gold}) | "
            f"{base_pres:.2f} | {sft_pres:.2f} | {missing_str} → {cats_str} |"
        )

        # Detailed block for diagnostic (input/output excerpts)
        detailed_blocks.append(f"### `{cid}` ({pdim} / {diff})\n")
        detailed_blocks.append(
            f"- input rows: {body_in}, sft output rows: {body_out}, gold rows: "
            f"{body_gold}"
        )
        detailed_blocks.append(
            f"- known_failure_modes (generator-seeded): "
            f"{case.get('known_failure_modes')}"
        )
        if missing_qs:
            detailed_blocks.append("- missing input rows in sft output:")
            for q in missing_qs:
                row_repr = ",".join(input_qmap_all[q][0])
                cat = categorize_missing_input_row(
                    input_qmap_all[q][0], in_header
                )
                detailed_blocks.append(f"    - `{row_repr}` → **{cat}**")
        detailed_blocks.append("")

    out.append("")
    out.append("## Aggregate classification\n")
    out.append(
        "Each row dropped by SFT but present in input is categorized by why it "
        "*might* have looked droppable to the model.\n"
    )
    out.append("| Category | Count |")
    out.append("|---|---|")
    for k in [
        "has_$M_notation",
        "has_orig_$M_in_notes",
        "extra_fabricated",
        "duplicate_in_input",
        "genuine_data",
    ]:
        out.append(f"| {k} | {classification_total.get(k, 0)} |")
    out.append("")
    out.append("## By primary_dimension\n")
    out.append("| dim | count of RH-like |")
    out.append("|---|---|")
    for k, v in sorted(by_pdim.items()):
        out.append(f"| {k} | {v} |")
    out.append("")

    out.append("## Detailed per-case rows\n")
    out.extend(detailed_blocks)

    # Compute the headline %s the user asked for
    total_lost = sum(
        classification_total.get(k, 0)
        for k in (
            "has_$M_notation",
            "has_orig_$M_in_notes",
            "extra_fabricated",
            "duplicate_in_input",
            "genuine_data",
        )
    )
    if total_lost == 0:
        total_lost = 1  # avoid div by zero
    pct_M = 100.0 * (
        classification_total.get("has_$M_notation", 0)
        + classification_total.get("has_orig_$M_in_notes", 0)
    ) / total_lost
    pct_dups = 100.0 * (
        classification_total.get("duplicate_in_input", 0)
        + classification_total.get("extra_fabricated", 0)
    ) / total_lost
    pct_genuine = 100.0 * classification_total.get("genuine_data", 0) / total_lost

    out.append("## Headline\n")
    out.append(
        f"Across the {len(rh_cases)} RH-like cases, of all dropped rows: "
        f"**{pct_M:.0f}%** had `$M` notation (raw or hidden in Notes), "
        f"**{pct_dups:.0f}%** were duplicates / fabricated entries the gold "
        f"would also drop, and **{pct_genuine:.0f}%** were genuinely lost data "
        f"with no defensible reason to drop."
    )
    out.append("")

    (ROOT / "docs" / "sft_v1_failure_audit.md").write_text(
        "\n".join(out), encoding="utf-8"
    )
    print(f"Wrote {(ROOT / 'docs' / 'sft_v1_failure_audit.md')}")
    print()
    print("Classification totals:")
    for k, v in classification_total.items():
        print(f"  {k}: {v}")
    print()
    print(f"Headline: $M-tagged={pct_M:.0f}%  dups/fab={pct_dups:.0f}%  "
          f"genuine={pct_genuine:.0f}%")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
